#!/usr/bin/env python3
"""Regenerates hooks/catalog.ts from the sibling mods' plugin.json files and their registered command names.
Run:  python3 tools/gen-catalog.py   (from the anim-extra folder). Read-only on the other mods."""
import glob, json, os, re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(HERE)

GROUPS = {
    'settings': 'settings',
    'looks': 'look', 'look-and-sound': 'look', 'layout': 'look', 'motion': 'look', 'animations': 'look',
    'anim-extra': 'look', 'tool-visuals': 'look', 'sound-pack': 'look',
    'tool-guard': 'safety', 'safety-pro': 'safety', 'controls': 'safety', 'alerts': 'safety',
    'workbench': 'work', 'cockpit': 'work', 'notes': 'work', 'git-kit': 'work', 'review-kit': 'work',
    'debug-kit': 'work', 'prompt-tools': 'work', 'prompting': 'work',
    'personality': 'fun', 'delight': 'fun', 'learning': 'fun', 'extras': 'fun',
}
# The command that prints each mod's help (read from the mods' own registrations and descriptions).
HELP = {
    'alerts': 'al', 'animations': 'anim', 'anim-extra': 'ax', 'cockpit': 'cockpit', 'controls': 'ct',
    'debug-kit': 'db', 'delight': 'dl', 'extras': 'cheats', 'git-kit': 'gk', 'layout': 'ly', 'learning': 'ln',
    'looks': 'look', 'motion': 'motion', 'notes': 'nt', 'personality': 'fun', 'prompt-tools': 'snip',
    'prompting': 'pm', 'review-kit': 'rk', 'safety-pro': 'protect', 'settings': 'cfg', 'sound-pack': 'sound',
    'tool-guard': 'readonly', 'tool-visuals': 'toolvis', 'workbench': 'dashboard',
}

mods = []
for d in sorted(os.listdir(ROOT)):
    p = os.path.join(ROOT, d, '.claude-plugin', 'plugin.json')
    if not os.path.isfile(p):
        continue
    try:
        j = json.load(open(p))
    except Exception:
        continue
    names = set()
    for f in glob.glob(os.path.join(ROOT, d, 'hooks', '*.ts*')):
        if '.test.' in f:
            continue
        names |= set(re.findall(r"(?:name|command):\s*'([a-z0-9]+)'", open(f).read()))
    help_cmd = HELP.get(d)
    if help_cmd is None:
        m = re.search(r"/([a-z]{2,6}) commands|starts? with ([a-z]{2,6})\b|prefix `?([a-z]{2,6})\b", str(j.get('description', '')))
        if m:
            help_cmd = next(g for g in m.groups() if g)
    if help_cmd is None and d != 'look-and-sound':
        short = sorted(names, key=lambda n: (len(n), n))
        help_cmd = short[0] if short else None
    desc = ' '.join(str(j.get('description', '')).split())
    mods.append({
        'name': j.get('name', d),
        'group': GROUPS.get(d, 'other'),
        'desc': desc,
        'help': help_cmd,
        'deps': list(j.get('dependencies', []) or []),
    })

out = [
    '// GENERATED by tools/gen-catalog.py from every mod folder next to this one. Do not edit by hand.',
    '// It is a snapshot taken at build time: a mod added later shows up after the script is run again.',
    "export type CatalogMod = { name: string; group: 'settings' | 'look' | 'safety' | 'work' | 'fun' | 'other'; desc: string; help: string | null; deps: string[] }",
    '',
    'export const CATALOG: readonly CatalogMod[] = [',
]
for m in mods:
    out.append('  ' + json.dumps(m, ensure_ascii=False) + ',')
out.append(']')
out.append('')
open(os.path.join(HERE, 'hooks', 'catalog.ts'), 'w').write('\n'.join(out))
print(len(mods), 'mods')
